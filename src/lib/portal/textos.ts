export type Textos = typeof ES;
export function textos(idioma: Idioma): Textos {
  return idioma === 'en' ? EN : ES;
}

/** dd/mm/aaaa (o mm/dd en inglés no: se usa dd MMM aaaa para evitar confusiones). */
export function fechaPortal(valor: string | null | undefined, idioma: Idioma): string {
  if (!valor) return '';
  const d = new Date(valor.length === 10 ? `${valor}T12:00:00` : valor);
  if (Number.isNaN(d.getTime())) return '';
  return d.toLocaleDateString(idioma === 'en' ? 'en-GB' : 'es-PE', {
    day: '2-digit', month: 'short', year: 'numeric', timeZone: 'America/Lima',
  });
}
